// Builds src/engine/wind/words.ts: the common English words Wind uses to check
// that a grid has one answer. One-off: reads the word list the LarpedIn project
// built from SCOWL (wordlist-english, Kevin Atkinson, permissive SCOWL licence)
// and keeps the three most common levels (SCOWL 10, 20, 35), 3 to 9 letters.
import { writeFileSync } from 'node:fs';
const { WEND_WORDS_PACKED } = await import('../../LarpedIN/src/data/wend-words.ts');
const words = [];
for (const b of WEND_WORDS_PACKED.split('\n').slice(0, 3)) {
  let prev = '', i = 0;
  while (i < b.length) {
    const k = b.charCodeAt(i++) - 48;
    let j = i;
    while (j < b.length && b.charCodeAt(j) >= 97) j++;
    const w = prev.slice(0, k) + b.slice(i, j);
    if (w.length <= 9) words.push(w);
    prev = w; i = j;
  }
}
words.sort();
let prev = '', out = '';
for (const w of new Set(words)) {
  let k = 0;
  while (k < prev.length && k < w.length && prev[k] === w[k]) k++;
  out += String.fromCharCode(48 + k) + w.slice(k);
  prev = w;
}
writeFileSync('src/engine/wind/words.ts',
  '// GENERATED by scripts/make-words.mjs; do not edit.\n' +
  '// Common English words from SCOWL (Copyright 2000-2016 Kevin Atkinson, SCOWL licence, permissive).\n' +
  '// Front-coded: one char (48 + letters shared with the previous word), then the rest of the word.\n' +
  `export const WORDS_PACKED = ${JSON.stringify(out)};\n`);
console.log(new Set(words).size, 'words', (out.length / 1024).toFixed(0), 'KB');
