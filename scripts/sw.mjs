// Writes dist/sw.js after a build so the app works offline.
//  - pages (home and one per game): network first (new releases show up at once), cache when offline
//  - hashed assets, icons, fonts: cache first (their names change when they change)
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const files = [];
const walk = (dir) => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (!['sw.js', '_headers', '.nojekyll', '404.html', 'robots.txt', 'sitemap.xml'].includes(f) && !/^og(-\w+)?\.png$/.test(f)) files.push(relative('dist', p)); } };
walk('dist');
const hash = createHash('sha1');
for (const f of files.sort()) hash.update(f).update(readFileSync(join('dist', f)));
const version = hash.digest('hex').slice(0, 10);
// pages are cached under their folder address (./trace/), the way they are visited
const precache = files.map((f) => (f === 'index.html' ? './' : f.endsWith('/index.html') ? `./${f.slice(0, -'index.html'.length)}` : `./${f}`));
writeFileSync('dist/sw.js', `// generated by scripts/sw.mjs
const CACHE = 'gamedin-${version}';
const FILES = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('gamedin-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    const page = new URL(req.url); page.search = ''; page.hash = '';
    e.respondWith(fetch(req).then((res) => {
      const copy = res.clone();
      if (res.ok) caches.open(CACHE).then((c) => c.put(page.href, copy));
      return res;
    }).catch(() => caches.match(page.href).then((hit) => hit || caches.match('./'))));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`);
console.log(`dist/sw.js: ${precache.length} files precached, version ${version}`);
