// Writes dist/sw.js after a build so the app works offline.
//  - the page itself: network first (new releases show up at once), cache when offline
//  - hashed assets, icons, fonts: cache first (their names change when they change)
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const files = [];
const walk = (dir) => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (!['sw.js', 'og.png', '_headers', '.nojekyll'].includes(f)) files.push(relative('dist', p)); } };
walk('dist');
const hash = createHash('sha1');
for (const f of files.sort()) hash.update(f).update(readFileSync(join('dist', f)));
const version = hash.digest('hex').slice(0, 10);
const precache = ['./', ...files.filter((f) => f !== 'index.html').map((f) => `./${f}`)];
writeFileSync('dist/sw.js', `// generated by scripts/sw.mjs
const CACHE = 'gamedin-${version}';
const FILES = ${JSON.stringify(precache)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('gamedin-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).then((res) => {
      const copy = res.clone();
      if (res.ok) caches.open(CACHE).then((c) => c.put('./', copy));
      return res;
    }).catch(() => caches.match('./')));
    return;
  }
  e.respondWith(caches.match(req, { ignoreSearch: true }).then((hit) => hit || fetch(req)));
});
`);
console.log(`dist/sw.js: ${precache.length} files precached, version ${version}`);
